/**
 * Workbench colors, named after VS Code's theme color ids (see [VsCodeTheme]
 * for the key mapping) so VS Code color themes can be loaded as-is.
 */
data class WorkbenchColors(
    val name: String,
    val isDark: Boolean,
    // Activity bar
    val activityBarBackground: Color,
    val activityBarForeground: Color,
    val activityBarInactiveForeground: Color,
    val activityBarActiveBorder: Color,
    // Side bar + lists
    val sideBarBackground: Color,
    val sideBarForeground: Color,
    val sideBarTitleForeground: Color,
    val sideBarSectionHeaderBackground: Color,
    val listActiveSelectionBackground: Color,
    val listHoverBackground: Color,
    // Editor
    val editorBackground: Color,
    val editorForeground: Color,
    val editorLineHighlight: Color,
    val editorSelection: Color,
    val editorCursor: Color,
    val editorLineNumber: Color,
    val editorLineNumberActive: Color,
    val editorIndentGuide: Color,
    val editorWhitespace: Color,
    val findMatchBackground: Color,
    val findMatchCurrentBackground: Color,
    val errorSquiggle: Color,
    val warningSquiggle: Color,
    val infoSquiggle: Color,
    val scrollbarSlider: Color,
    val minimapSliderBackground: Color,
    // Tabs + breadcrumbs
    val editorGroupHeaderBackground: Color,
    val tabActiveBackground: Color,
    val tabInactiveBackground: Color,
    val tabActiveForeground: Color,
    val tabInactiveForeground: Color,
    val tabBorder: Color,
    val tabActiveBorderTop: Color,
    val breadcrumbForeground: Color,
    // Panel
    val panelBackground: Color,
    val panelBorder: Color,
    val panelTitleActiveForeground: Color,
    val panelTitleInactiveForeground: Color,
    val panelTitleActiveBorder: Color,
    // Status bar
    val statusBarBackground: Color,
    val statusBarForeground: Color,
    // Inputs, widgets
    val focusBorder: Color,
    val inputBackground: Color,
    val inputForeground: Color,
    val inputBorder: Color,
    val inputValidationErrorBackground: Color,
    val inputValidationErrorBorder: Color,
    val quickInputBackground: Color,
    val widgetShadow: Color,
    val badgeBackground: Color,
    val badgeForeground: Color,
    val keybindingLabelBackground: Color,
    val keybindingLabelForeground: Color,
    val keybindingLabelBorder: Color,
    val keybindingLabelBottomBorder: Color,
    val buttonBackground: Color,
    val buttonForeground: Color,
    val descriptionForeground: Color,
    val textLinkForeground: Color,
    val errorForeground: Color,
    val warningForeground: Color,
    // Menus (context menu, the selection toolbar)
    val menuBackground: Color,
    val menuForeground: Color,
    val menuBorder: Color,
    val menuSelectionBackground: Color,
    val menuSelectionForeground: Color,
    val menuSeparator: Color,
    /** Syntax colors per highlight class (from `tokenColors`). */
    val tokens: Map<StyleKind, Color>,
    /**
     * Per-token styles from a VS Code theme's `tokenColors`, matched against
     * each token's TextMate scope stack like VS Code does. Built-in themes use
     * [tokens] for colors and only take font styles (Markdown bold/italic) from here.
     */
    val tokenStyles: TokenStyles = TokenStyles.builtInFontStyles,
    /** Colors from [tokens] (built-in themes) rather than [tokenStyles]. */
    val kindColors: Boolean = true,
    /** Every color a VS Code theme sets, by its id, for views with their own colors (Source Control, diff). */
    val themeColors: Map<String, Color> = emptyMap(),
) {
    fun token(kind: StyleKind): Color = tokens[kind] ?: editorForeground

    /** A theme color by VS Code id, or [default] when the theme doesn't set it. */
    fun color(id: String, default: Color): Color = themeColors[id] ?: default
}

val LocalWorkbenchColors = staticCompositionLocalOf { DarkModern }

private fun c(hex: Long) = Color(hex)

